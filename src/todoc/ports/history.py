"""Порт бэкенда истории.

Две реализации — ``embedded`` (снимки в ``.todoc/history/objects/``) и ``git`` (содержимое
«до» берётся из репозитория). Порт нужен, чтобы ядро не знало, где именно лежит образ:
``application/history.py`` работает только с этими четырьмя методами.

Git здесь — опциональный бэкенд, а не зависимость (P2, P12): вызов внешнего бинарника
происходит только внутри ``GitBackend``, и при его отсутствии датасет деградирует в
``embedded``, а не ломается.
"""

from __future__ import annotations

from typing import Protocol


class HistoryBackend(Protocol):
    """Где хранится образ файла «до» изменения."""

    #: Имя для ``dataset.json`` и диагностик: ``embedded`` | ``git``.
    name: str

    def available(self) -> bool:
        """Можно ли пользоваться этим бэкендом прямо сейчас."""

    def head(self) -> str | None:
        """Опорная точка бэкенда на момент вызова (для git — HEAD)."""

    def read_at(self, revision: str | None, rel_path: str) -> bytes | None:
        """Содержимое ``rel_path`` на ревизии ``revision``; None, если недоступно."""

    def needs_snapshot(self, rel_path: str, last_revision: str | None) -> bool:
        """Нужно ли писать собственный снимок для этого файла.

        ``embedded`` отвечает всегда «да». ``git`` — только когда прошлое состояние
        недостижимо из репозитория, то есть когда у прошлого события по этому пути та же
        опора (правило gap-filling из §18 плана): иначе незакоммиченные промежуточные
        правки были бы потеряны.
        """
